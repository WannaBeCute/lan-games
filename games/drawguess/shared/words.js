/** 每个类别至少 50 条 —— 自检用 */
function wordCount(cat) { return cat.words.length; }

/** 打平成 [{ text, cat, origin }] */
function allWords() {
  const out = [];
  for (const cat of CATEGORIES) {
    for (const raw of cat.words) {
      const i = raw.indexOf('|');
      const text = (i < 0 ? raw : raw.slice(0, i)).trim();
      const origin = (i < 0 ? cat.origin : raw.slice(i + 1).trim()) || cat.origin;
      out.push({ text: text, cat: cat.name, origin: origin });
    }
  }
  return out;
}

/** 类别名清单（大厅勾选用，默认全选） */
function categoryNames() { return CATEGORIES.map(function (c) { return c.name; }); }

